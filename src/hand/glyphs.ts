const BASIC = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ()[]{}|+-=/<>.,!*^_';
let cache: Glyph[] | null = null;
/** every template glyph (Hershey first, then the hand-drawn ones) */
export function allGlyphs(): Glyph[] {
  if (cache) return cache;
  const out: Glyph[] = [];
  for (const ch of BASIC) {
    const d = HERSHEY[ch];
    if (d) out.push({ ch, strokes: hersheyStrokes(d) });
  }
  out.push(...EXTRA);
  cache = out;
  return out;
}
