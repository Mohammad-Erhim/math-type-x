/**
 * Stroke glyphs of the handwriting recogniser (templates) and of the stroke simulation.
 * Coordinates are Hershey units: the baseline is y = 22, the cap height 21 (top y = 1), x grows to the right.
 * Letters and digits come from the Hershey single-stroke font; the symbols below are drawn by hand and add the
 * variants people write differently (open / closed 4, 7 with a bar, single-storey a, one-stroke x …).
 */
import { HERSHEY } from './hershey';

export type Pt = [number, number];
export interface Glyph {
  ch: string;
  strokes: Pt[][];
}

/** polylines of a Hershey glyph path ("M x,y L x,y x,y M …") */
export function hersheyStrokes(d: string): Pt[][] {
  return d
    .split('M')
    .slice(1)
    .map((part) => part.replace(/L/g, ' ').trim().split(/\s+/).map((p) => p.split(',').map(Number) as Pt));
}

/** points of an ellipse arc (degrees, 0 = right, 90 = up on the screen) */
function arc(cx: number, cy: number, rx: number, ry: number, from: number, to: number, n = 14): Pt[] {
  const out: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const a = ((from + ((to - from) * i) / n) * Math.PI) / 180;
    out.push([cx + rx * Math.cos(a), cy - ry * Math.sin(a)]);
  }
  return out;
}
const dot = (x: number, y: number): Pt[] => [[x, y - 0.4], [x, y + 0.4]];

